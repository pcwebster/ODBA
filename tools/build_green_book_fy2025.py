"""Build a stand-alone FY2025 Green Book Table 6-10 sidecar."""
import argparse
import csv
import io
import json
import re
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1] / "data/green_book/fy2025"
BUDGET_COLUMNS = ("source_vintage_fy", "funding_fy", "source_year_status",
                  "military_department", "row_grain", "dollar_basis", "unit",
                  "budget_authority", "funding_scope", "source_table",
                  "source_printed_page", "source_url", "reconciliation_status")
QA_COLUMNS = ("funding_fy", "dollar_basis", "published_total_usd_m",
              "component_sum_usd_m", "difference_usd_m", "reconciliation_status")
COMPONENTS = ("Army", "Navy", "Air Force", "Defense-Wide")
BASIS = ("Current", "Constant FY2025")
EXPECTED_EXCEPTIONS = {(2003, "Current"): 500, (2011, "Current"): 4999,
                       (2029, "Current"): 4}


def csv_text(header, rows):
    out = io.StringIO(newline="")
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return out.getvalue()


def year_status(year):
    if year <= 2023:
        return "Historical"
    if year == 2024:
        return "Continuing resolution"
    if year == 2025:
        return "President's Budget"
    return "Outyear estimate"


def build(source):
    obj = json.loads(source.read_text(encoding="utf-8"))
    if (obj["source_vintage_fy"], obj["source_table"]) != (2025, "6-10"):
        raise ValueError("Unexpected source edition or table")
    pages = obj["pages"]
    if [p["printed_page"] for p in pages] != list(range(154, 162)):
        raise ValueError("Incomplete source pages")
    facts, qa, historical, years, exceptions = [], [], [], [], {}
    for page in pages:
        page_years = [int(re.fullmatch(r"FY (\d{4})(?: CR\*)?", h.strip())[1])
                      for h in page["header"].split("|")[1:]]
        years.extend(page_years)
        if len(page["rows"]) != 10:
            raise ValueError("Unexpected row count")
        for b, basis in enumerate(BASIS):
            raw_rows = [r.split("|") for r in page["rows"][5*b:5*b+5]]
            total_name = "Total Constant Dollars" if b else "Total Current Dollars"
            if tuple(r[0].strip() for r in raw_rows) != COMPONENTS + (total_name,):
                raise ValueError("Unexpected row labels or order")
            if any(len(r) != 1+len(page_years) for r in raw_rows):
                raise ValueError("Unexpected cell count")
            for col, year in enumerate(page_years, start=1):
                amounts = [int(r[col].strip().replace(",", "")) for r in raw_rows]
                component_sum = sum(amounts[:4])
                delta = component_sum - amounts[-1]
                flag = "Within rounding tolerance"
                if abs(delta) > 2:
                    exceptions[year, basis] = delta
                    flag = "Review exception"
                qa.append((year, basis, amounts[-1], component_sum, delta, flag))
                status = year_status(year)
                for i, amount in enumerate(amounts):
                    fact = (2025, year, status,
                            COMPONENTS[i] if i < 4 else "DoD total",
                            "Component" if i < 4 else "Published total", basis,
                            "USD millions", amount, "Discretionary and mandatory",
                            "6-10", page["printed_page"], obj["source_url"], flag)
                    facts.append(fact)
                    if status == "Historical" and abs(delta) <= 2:
                        historical.append(fact)
    if years != list(range(1948, 2030)):
        raise ValueError("Missing, duplicated or out-of-order fiscal years")
    if exceptions != EXPECTED_EXCEPTIONS:
        raise ValueError(f"Unexpected reconciliation exceptions: {exceptions}")
    if (len(facts), len(qa), len(historical)) != (820, 164, 750):
        raise ValueError("Unexpected output cardinality")
    if len({(r[1], r[3], r[5]) for r in facts}) != len(facts):
        raise ValueError("Duplicate fact grain")
    return {
        "budget_authority.csv": csv_text(BUDGET_COLUMNS, facts),
        "historical_qa_passed.csv": csv_text(BUDGET_COLUMNS, historical),
        "reconciliation.csv": csv_text(QA_COLUMNS, qa),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE / "table_6_10_indexed.json")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--out-dir", type=Path)
    group.add_argument("--check", type=Path, help="Compare regenerated bytes to this directory.")
    args = parser.parse_args()
    output = build(args.source)
    if args.check:
        for filename, content in output.items():
            if (args.check / filename).read_bytes() != content.encode("utf-8"):
                raise SystemExit(f"Mismatch: {filename}")
    else:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for filename, content in output.items():
            (args.out_dir / filename).write_bytes(content.encode("utf-8"))


if __name__ == "__main__":
    main()
